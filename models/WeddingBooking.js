const mongoose = require("mongoose");

const STAGES = [
  "inquiry", "package_offer", "interested", "event_details", "hall_check",
  "proposal", "advance_payment", "agreement", "cs_verification", "confirmed",
  "finalization", "reminder", "event_setup", "executed", "feedback",
  "follow_up", "no_booking",
];
const CORPORATE_STAGES = [
  "inquiry", "interested", "event_details", "hall_check", "proposal",
  "advance_payment", "agreement", "cs_verification", "confirmed",
  "reminder", "event_setup", "executed", "feedback", "follow_up", "no_booking",
];

const weddingBookingSchema = new mongoose.Schema({
  restaurantId: { type: String, required: true, trim: true, index: true },
  bookingType: { type: String, enum: ["wedding", "corporate"], default: "wedding", index: true },
  customerName: { type: String, default: "", trim: true, maxlength: 160 },
  customerPhone: { type: String, required: true, trim: true, index: true },
  customerEmail: { type: String, default: "", trim: true, lowercase: true },
  stage: { type: String, enum: STAGES, default: "inquiry", index: true },
  stageHistory: [{
    stage: { type: String, enum: STAGES, required: true },
    changedAt: { type: Date, default: Date.now },
    changedBy: { type: mongoose.Schema.Types.ObjectId, ref: "Admin", default: null },
    actorName: { type: String, default: "WhatsApp AI" },
    note: { type: String, default: "", maxlength: 500 },
  }],
  answers: {
    weddingDate: { type: String, default: "" },
    eventType: { type: String, default: "" },
    guests: { type: Number, min: 0, default: null },
    startTime: { type: String, default: "" },
    endTime: { type: String, default: "" },
    hallPreference: { type: String, default: "" },
    seatingSetup: { type: String, default: "" },
    menuService: { type: String, default: "" },
    specialDishes: { type: String, default: "" },
    dietaryNeeds: { type: String, default: "" },
    stageDecor: { type: String, default: "" },
    avNeeds: { type: String, default: "" },
    eventDate: { type: String, default: "" },
    eventPurpose: { type: String, default: "" },
    preferredVenueSetup: { type: String, default: "" },
    eventTiming: { type: String, default: "" },
    menuPreference: { type: String, default: "" },
    seatingArrangement: { type: String, default: "" },
    companyName: { type: String, default: "" },
    contactPerson: { type: String, default: "" },
    contactPhone: { type: String, default: "" },
    specialRequirements: { type: String, default: "" },
  },
  currentQuestionIndex: { type: Number, min: 0, max: 11, default: 0 },
  awaitingHallChoice: { type: Boolean, default: false },
  interested: { type: Boolean, default: null },
  followUpAt: { type: Date, default: null, index: true },
  hallId: { type: mongoose.Schema.Types.ObjectId, ref: "WeddingHall", default: null, index: true },
  hallName: { type: String, default: "", trim: true },
  setupType: { type: String, default: "" },
  alternateDates: [{ type: String }],
  acceptedAlternateDate: { type: String, default: "" },
  packageName: { type: String, default: "", trim: true },
  menuPackageId: { type: mongoose.Schema.Types.ObjectId, default: null },
  selectedMenuName: { type: String, default: "", trim: true },
  quotation: {
    guests: { type: Number, default: 0 },
    menuPricePerPerson: { type: Number, default: 0 },
    menuSubtotal: { type: Number, default: 0 },
    hallRental: { type: Number, default: 0 },
    decorCost: { type: Number, default: 0 },
    addOns: [{ label: String, quantity: Number, unitPrice: Number, total: Number }],
    discount: { type: Number, default: 0 },
    taxPercent: { type: Number, default: 0 },
    taxAmount: { type: Number, default: 0 },
    total: { type: Number, default: 0 },
    advanceRequired: { type: Number, default: 0 },
    rulesApplied: [{ type: String }],
    notes: { type: String, default: "" },
    generatedAt: { type: Date, default: null },
  },
  paymentProofUrl: { type: String, default: "" },
  paymentVerified: { type: Boolean, default: false },
  paymentVerifiedAt: { type: Date, default: null },
  paymentVerifiedBy: { type: mongoose.Schema.Types.ObjectId, ref: "Admin", default: null },
  paymentStatus: { type: String, enum: ["unpaid", "proof_received", "verified"], default: "unpaid" },
  confirmationMessageStatus: { type: String, enum: ["pending", "sent", "failed"], default: "pending" },
  confirmationMessageError: { type: String, default: "", maxlength: 500 },
  agreementUrl: { type: String, default: "" },
  agreementSentAt: { type: Date, default: null },
  reminderScheduledAt: { type: Date, default: null },
  reminderWarning: { type: String, default: "" },
  finalization: {
    decorTheme: { type: String, default: "" },
    tastingNotes: { type: String, default: "" },
    hallSetup: { type: String, default: "" },
    avChecklist: { type: String, default: "" },
  },
  eventExecutionNotes: { type: String, default: "" },
  feedback: { type: String, default: "" },
  aiReplies: [{
    questionIndex: { type: Number, default: null },
    text: { type: String, default: "" },
    reviewed: { type: Boolean, default: false },
    createdAt: { type: Date, default: Date.now },
  }],
  source: { type: String, enum: ["whatsapp", "crm"], default: "whatsapp" },
}, { timestamps: true });

weddingBookingSchema.index({ restaurantId: 1, stage: 1, updatedAt: -1 });
weddingBookingSchema.index({ restaurantId: 1, customerPhone: 1, createdAt: -1 });

weddingBookingSchema.statics.stages = STAGES;

module.exports = mongoose.model("WeddingBooking", weddingBookingSchema);
